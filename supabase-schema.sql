-- สร้างโปรไฟล์ให้อัตโนมัติหลังสมัครด้วย Supabase Auth
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_type text := coalesce(new.raw_user_meta_data->>'account_type', 'school');
  v_student_number text := coalesce(new.raw_user_meta_data->>'student_number', '');
  v_class_code text := coalesce(new.raw_user_meta_data->>'class_code', '');
  v_year smallint := coalesce(nullif(new.raw_user_meta_data->>'academic_year', '')::smallint, 2569);
begin
  if v_type not in ('school', 'external') then
    raise exception 'ประเภทบัญชีไม่ถูกต้อง';
  end if;
  if v_type = 'school' then
    if v_student_number !~ '^[0-9]{5}$' then
      raise exception 'ต้องใช้รหัสนักเรียน 5 หลัก';
    end if;
    if v_class_code not in ('1/1','1/2','2/1','2/2','2/3','2/4','3/1','3/2','3/3','4/1','4/2','4/3','5/1','5/2','6/1','6/2') then
      raise exception 'ชั้น/ห้องไม่ถูกต้อง';
    end if;
  else
    if v_student_number !~ '^EXT-[0-9a-fA-F-]{36}$' then
      raise exception 'รหัสบัญชีภายนอกไม่ถูกต้อง';
    end if;
    if char_length(v_class_code) not between 1 and 40 then
      raise exception 'กรุณาระบุระดับชั้น 1–40 ตัวอักษร';
    end if;
    if v_year not between 2500 and 2700 then
      raise exception 'ปีการศึกษาต้องอยู่ระหว่าง 2500–2700';
    end if;
  end if;
  insert into public.profiles (id, full_name, student_number, class_code, roll_number, account_type, academic_year, brand_logo_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    v_student_number,
    v_class_code,
    case when v_type = 'school' then nullif(new.raw_user_meta_data->>'roll_number', '')::smallint else null end,
    v_type,
    v_year,
    nullif(new.raw_user_meta_data->>'brand_logo', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();
