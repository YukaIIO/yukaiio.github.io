drop index if exists public.class_schedules_personal_unique;
create unique index class_schedules_shared_unique on public.class_schedules(academic_year, semester, class_code, coalesce(study_track, '')) where owner_id is null;
create unique index class_schedules_personal_unique on public.class_schedules(owner_id, academic_year, semester, class_code, coalesce(study_track, '')) where owner_id is not null;

