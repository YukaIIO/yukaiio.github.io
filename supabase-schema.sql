create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(full_name) between 2 and 100),
  student_number text not null unique check (student_number ~ '^[0-9]{5}$'),
  class_code text,
  roll_number smallint check (roll_number between 1 and 60),
  avatar_data text check (avatar_data is null or char_length(avatar_data) <= 1500000),
  -- รองรับบัญชีนักเรียนโรงเรียนและบัญชีภายนอก โดยแยกข้อมูลตารางส่วนตัวตามเจ้าของ
  account_type text not null default 'school' check (account_type in ('school','external')),
  academic_year smallint not null default 2569 check (academic_year between 2500 and 2700),
  brand_logo_url text,
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists class_code text;
alter table public.profiles add column if not exists roll_number smallint;
alter table public.profiles add column if not exists avatar_data text;
alter table public.profiles add column if not exists account_type text not null default 'school';
alter table public.profiles add column if not exists academic_year smallint not null default 2569;
alter table public.profiles add column if not exists brand_logo_url text;

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  subject text not null,
  due_date date,
  due_time time,
  status text not null default 'pending' check (status in ('pending', 'progress', 'done')),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


create table if not exists public.class_schedules (
  id bigint generated by default as identity primary key,
  academic_year smallint not null check (academic_year between 2500 and 2700),
  semester smallint not null check (semester in (1, 2)),
  class_code text not null check (class_code in ('1/1','1/2','2/1','2/2','2/3','2/4','3/1','3/2','3/3','4/1','4/2','4/3','5/1','5/2','6/1','6/2')),
  study_track text check (study_track in ('science-math','general')),
  owner_id uuid references auth.users(id) on delete cascade,
  schedule_data jsonb not null check (jsonb_typeof(schedule_data) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.class_schedules add column if not exists study_track text;
